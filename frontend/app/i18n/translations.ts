/**
 * Helper to fetch localized string with fallback.
 */
export function getTranslation(key: string, lang: SupportedLanguage = 'am'): string {
  if (translations[lang] && translations[lang][key]) {
    return translations[lang][key];
  }
  // Fallbacks: Amharic -> English -> key
  if (translations['am'] && translations['am'][key]) {
    return translations['am'][key];
  }
  if (translations['en'] && translations['en'][key]) {
    return translations['en'][key];
  }
  return key;
}
